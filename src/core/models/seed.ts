import type { CostTier, ModelRecord, PeakPricing } from "../types.js"
import { OPENDESIGN_MODELS } from "../providers/opendesign-models.js"

export interface SeedModel {
  key: string
  providerID: string
  modelID: string
  name: string
  context: number
  maxOutput: number
  input: string[]
  tools?: boolean
  cost: CostTier[]
  peakPricing?: PeakPricing
  intelligence: number
  design: number
  designEvidence?: ModelRecord["designEvidence"]
  /** Credit multiplier applied to usage value. One for plain USD billing. */
  creditMultiplier?: number
  premium?: boolean
  training?: boolean
  free?: boolean
  tier: 1 | 2 | 3
  approved?: boolean
  monthlyAllowanceUsd: number
  notes?: string
}

const cost = (input: number, output: number, read: number, write = 0): CostTier[] => [
  { input, output, cache: { read, write } },
]

const tieredCost = (
  base: CostTier,
  size: number,
  high: { input: number; output: number; read: number; write: number },
): CostTier[] => [
  base,
  {
    input: high.input,
    output: high.output,
    cache: { read: high.read, write: high.write },
    tier: { type: "context", size },
  },
]

